// 表示専用の整形。公式PDF由来の questionText のデータには手を加えず、
// 描画時に「ア〜オの記述」の開始位置へ改行を差し込むだけ（変化は改行の挿入のみ）。
// OCRで改行が失われた組み合わせ問題（例: 令和7年度 問26）を読みやすくする。
//
// パターンの根拠: 全250問の「カタカナ1文字＋空白」の出現箇所を機械抽出して全数目視し、
// 記述ラベル（ア/イ/ウ/エ/オ）以外に該当が無いことを確認済み。
// 直後が数字・読点・句点の場合（「1 ア、エ」等の選択肢内の列挙）は除外する。
const ITEM_HEAD = /([^\nアイウエオ])([アイウエオ])([ 　])(?![0-9０-９、。])/g;

export const formatQuestionText = (text: string): string =>
  text.replace(ITEM_HEAD, "$1\n\n$2$3");
